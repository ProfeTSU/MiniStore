    private void btnReponerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReponerActionPerformed
        // TODO add your handling code here:
        // El controlador decide QUÉ productos (necesitaReposicion);
        // la ventana solo arma el texto y lo muestra.
        ArrayList<Producto> lista = controlador.productosParaReponer();
        if (lista.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ningún producto necesita reposición");
            return;
        }
        String texto = "Productos con stock en el mínimo o por debajo:\n\n";
        for (Producto p : lista) {
            texto += p.getCodigo() + " - " + p.getNombre()
                   + ": stock " + p.getStock() + " (mínimo " + p.getStockMinimo() + ")\n";
        }
        JOptionPane.showMessageDialog(this, texto, "Productos para reponer", JOptionPane.WARNING_MESSAGE);
    }//GEN-LAST:event_btnReponerActionPerformed

