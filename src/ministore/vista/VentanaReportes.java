    // Llena las dos tablas y los dos totales con el periodo elegido.
    private void generarReporte() {
        int periodo = cmbPeriodo.getSelectedIndex();             // La POSICIÓN elegida.
        if (!controlador.periodoValido(periodo)) {
            JOptionPane.showMessageDialog(this, "Seleccione un periodo");
            return;
        }

        modeloVentas.setRowCount(0);             // Borra las filas anteriores.
        for (Object[] fila : controlador.ventasPorPeriodo(periodo)) {
            fila[4] = String.format("%.2f", (double) fila[4]);  // El total, con dos decimales.
            modeloVentas.addRow(fila);           // La fila ya viene en el orden de las columnas.
        }

        modeloMasVendidos.setRowCount(0);
        for (Object[] fila : controlador.productosMasVendidos(periodo)) {
            modeloMasVendidos.addRow(fila);
        }

        lblTotalVendido.setText(String.format("Total vendido: $%.2f", controlador.totalVendido(periodo)));
        lblUtilidad.setText(String.format("Utilidad: $%.2f", controlador.utilidad(periodo)));
    }

