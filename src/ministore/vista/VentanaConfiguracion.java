    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        // La vista solo LEE lo que escribió el usuario, se lo PASA al
        // controlador y MUESTRA la respuesta. Las validaciones las hace el controlador.
        String mensaje = controlador.actualizarTienda(
                txtNombre.getText(),
                txtNit.getText(),
                txtDireccion.getText(),
                txtTelefono.getText());
        JOptionPane.showMessageDialog(this, mensaje);
        if (mensaje.startsWith("Datos de la tienda")) {   // El éxito empieza así; los errores no.
            dispose();                                     // Guardado: se cierra la ventana.
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

