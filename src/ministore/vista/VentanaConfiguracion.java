    // Muestra en los campos los datos actuales de la tienda.
    // Si la tabla está vacía, avisa y desactiva Guardar (no hay qué actualizar).
    private void cargarDatos() {
        Tienda t = controlador.obtenerTienda();
        if (t == null) {
            JOptionPane.showMessageDialog(this, "No hay datos de la tienda. Ejecute el script 02");
            btnGuardar.setEnabled(false);
            return;
        }
        txtNombre.setText(t.getNombre());
        txtNit.setText(t.getNit());
        txtDireccion.setText(t.getDireccion());
        txtTelefono.setText(t.getTelefono());
    }

